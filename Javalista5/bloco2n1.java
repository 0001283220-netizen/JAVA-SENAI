package Javalista5;

public class bloco2n1  {
    public static void main(String[] args) {

        int i = 1;
        int soma = 0;

        while (i <= 10) {
            soma = soma + i;
            i++;
        }

        System.out.println("A soma de 1 a 10 é: " + soma);
    }
}

